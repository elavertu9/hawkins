// Tag filters on the recipes page, alone and with a course.
import { BASE, open } from "./lib.mjs";

const { send, ev, go, sleep, check, shot, errors, finish } = await open();
const visible = "[...document.querySelectorAll('.card')].filter(c => !c.hidden).map(c => c.querySelector('.card__title').textContent.trim())";
const status = "document.querySelector('[data-status]').textContent";
const counts = "[...document.querySelectorAll('.chip')].map(c => c.textContent.replace(/\\s+/g,' ').trim()).join(' | ')";
const click = (sel) => ev(`document.querySelector('${sel}').click()`).then(() => sleep(150));
await send("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 2, mobile: true });
await go("/recipes/");
check(`initial: ${await ev(status)}`, (await ev(status)) === "46 recipes");
await click('.chip[data-tag="low-calorie"]');
check(`Low Calorie: ${await ev(visible)} | ${await ev("location.search")}`, (await ev(visible)).join() === "Cottage Cheese Bagels" && (await ev("location.search")) === "?tag=low-calorie");
check(`counts with tag: ${await ev(counts)}`, /All 1 \| Appetizer 0 \| Breakfast 1/.test(await ev(counts)));
await click('.chip[data-category="breakfast"]');
check(`Breakfast + Low Calorie: ${await ev(visible)} | ${await ev("location.search")}`, (await ev(visible)).length === 1 && /category=breakfast&tag=low-calorie/.test(await ev("location.search")));
await shot("tags-mobile");
await click('.chip[data-category="dinner"]');
check(`Dinner + Low Calorie -> empty: ${await ev("!document.querySelector('[data-empty]').hidden")}`, (await ev(visible)).length === 0);
await click('[data-clear]');
check(`clear resets tag too: ${await ev(status)}`, (await ev(status)) === "46 recipes");
await click('.chip[data-category="breakfast"]');
check(`Breakfast: ${await ev(visible)} | tag count ${await ev("document.querySelector('.chip[data-tag] [data-count]').textContent")}`, (await ev(visible)).length === 3);
await click('.chip[data-tag="low-calorie"]'); await click('.chip[data-tag="low-calorie"]');
check(`tag toggles off: ${(await ev(visible)).length} breakfasts`, (await ev(visible)).length === 3 && (await ev("location.search")) === "?category=breakfast");
await ev("(() => { const i = document.querySelector('#recipe-search'); i.value = 'bagel'; i.dispatchEvent(new Event('input')); })()"); await sleep(150);
await click('[data-clear]');
await ev("(() => { const i = document.querySelector('#recipe-search'); i.value = 'low calorie'; i.dispatchEvent(new Event('input')); })()"); await sleep(150);
check(`search "low calorie": ${await ev(visible)}`, (await ev(visible)).join() === "Cottage Cheese Bagels");
await go("/recipes/cottage-cheese-bagels/");
check(`recipe eyebrow: ${await ev("document.querySelector('.recipe-hero .eyebrow').textContent.replace(/\\s+/g,' ').trim()")}`, /Breakfast Low Calorie/.test(await ev("document.querySelector('.recipe-hero .eyebrow').textContent.replace(/\\s+/g,' ').trim()")));
check(`calories: ${await ev("[...document.querySelectorAll('.stat')].map(s => s.textContent.replace(/\\s+/g,' ').trim()).join(' | ')")}`, /CALORIES 186/i.test(await ev("[...document.querySelectorAll('.stat')].map(s => s.textContent.replace(/\\s+/g,' ').trim()).join(' | ')")));
await shot("bagels-mobile");
await click('.recipe-hero .tag'); await sleep(1300);
check(`tag link -> ${await ev("location.pathname + location.search")}: ${await ev(visible)}`, (await ev(visible)).join() === "Cottage Cheese Bagels");
check("fits", await ev("document.documentElement.scrollWidth <= innerWidth"));
await send("Emulation.setDeviceMetricsOverride", { width: 1280, height: 900, deviceScaleFactor: 1, mobile: false });
await go("/recipes/");
await shot("tags-desktop");
check(`JS errors: ${errors.length} ${errors.join(' | ')}`, errors.length === 0);
finish();
